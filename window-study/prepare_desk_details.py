def fabric(name, base):
    # Build one repeat tile of crossed yarn bundles. The mesh UVs below are in
    # physical metres, so the knit remains finer than the stitched binding.
    size = 128
    y, x = np.mgrid[:size, :size] / size * 2 * np.pi
    warp, weft = np.cos(x * 14), np.cos(y * 10 + .63 * np.sin(x * 7))
    crossings = np.tanh(np.cos(x * 7) * np.cos(y * 5) * 4)
    relief = np.maximum(warp * (.70 + .23 * crossings), weft * (.68 - .23 * crossings))
    grain = np.random.default_rng(209).uniform(-1, 1, warp.shape)
    srgb = (np.array(base)[None, None, :] + (7 * relief + 1.7 * grain)[:, :, None]) / 255
    # Byte-backed generated images are packed as sRGB bytes by Blender.
    img = bpy.data.images.new(name + ' yarn', width=size, height=size, alpha=False)
    img.pixels.foreach_set(np.dstack((srgb, np.ones((size, size)))).astype('float32').ravel())
    img.pack()
    mat = mats[name]
    shader = mat.node_tree.nodes.get('Principled BSDF')
    tex = mat.node_tree.nodes.new('ShaderNodeTexImage')
    tex.image = img
    mat.node_tree.links.new(tex.outputs['Color'], shader.inputs['Base Color'])


