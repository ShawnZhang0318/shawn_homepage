def add(mat, vs, fs, uv=None):
    verts, faces, uvs = geometry[prop, mat]
    i = len(verts)
    vs = np.asarray(vs, float).reshape(-1, 3)
    verts.extend(vs.tolist())
    faces.extend(tuple(int(j) + i for j in face) for face in fs)
    uvs.extend((np.zeros((len(vs), 2)) if uv is None else uv).tolist())


def unit(v):
    v = np.asarray(v, float)
    return v / np.linalg.norm(v)


def superpoint(v, power):
    return np.sign(v) * abs(v) ** power


def basis(axis):
    x = unit(np.cross(axis, Z if abs(axis[2]) < .9 else Y))
    return x, np.cross(axis, x)


def skin(mat, rows, uvaxis=None, close=True):
    rows = np.array(rows)
    k, n = rows.shape[:2]
    # Two triangles on n-gon end caps are not enough for sculpted chair crowns;
    # their concentric top rings are generated by the caller.
    faces = [(j*n+i, j*n+(i+1)%n, (j+1)*n+(i+1)%n, (j+1)*n+i)
             for j in range(k-1) for i in range(n)]
    if close:
        faces.extend([tuple(reversed(range(n))), tuple(range((k-1)*n, k*n))])
    vs = rows.reshape(-1, 3)
    uv = None if uvaxis is None else vs[:, uvaxis] / .026
    add(mat, vs, faces, uv)


def turned(mat, center, axis, profile, n=48):
    center, axis = np.asarray(center), unit(axis)
    u, v = basis(axis)
    ring = np.array([u*math.cos(t) + v*math.sin(t) for t in np.arange(n)*2*np.pi/n])
    skin(mat, [center + axis*h + r*ring for h, r in profile])


def rail(mat, path, side, dimensions, exponent=.65, n=16):
    path = np.asarray(path, float)
    rows = []
    a = np.arange(n)*2*np.pi/n
    for i,p in enumerate(path):
        tangent = unit(path[min(len(path)-1,i+1)] - path[max(0,i-1)])
        side_axis = unit(side - np.dot(side,tangent)*tangent)
        depth_axis = np.cross(tangent,side_axis)
        w,h = dimensions[i]
        rows.append(p+w*superpoint(np.cos(a),exponent)[:,None]*side_axis+
                    h*superpoint(np.sin(a),exponent)[:,None]*depth_axis)
    skin(mat, rows)


def swept(mat, path, radius, closed=False, n=8):
    path = np.asarray(path)
    rows = []
    for i,p in enumerate(path):
        prev = path[(i-1)%len(path)] if closed or i else p
        after = path[(i+1)%len(path)] if closed or i < len(path)-1 else p
        u, v = basis(unit(after-prev))
        rows.append([p+radius*(u*np.cos(t)+v*np.sin(t)) for t in np.arange(n)*2*np.pi/n])
    if closed:
        rows.append(rows[0])
    skin(mat, rows, close=not closed)


def bolt(p, axis, radius):
    axis = unit(axis)
    turned(steel,p,axis,[(0,radius),(.0006,radius),(.0012,radius*.87)],24)
    turned(inset,np.asarray(p)+axis*.00122,axis,[(0,radius*.48),(.00008,radius*.48)],6)


def reuse(p, mat):
    add(mat, p['vertices'], p['faces'])


def seat():
    a = np.arange(80)*2*np.pi/80
    x, y = superpoint(np.cos(a),.56), superpoint(np.sin(a),.56)
    def ring(f,z):
        # Broader support at the front, a shallow ischial pocket aft and
        # raised outer bolsters blended into a rolled waterfall leading edge.
        xx, yy = x*f, y*f
        top = .018*xx**2 - .015*np.exp(-((xx/.65)**2+((yy-.28)/.50)**2)) - .013*np.maximum(-yy,0)**4
        return np.stack([2.8+(.262-.014*yy)*xx,1.284+yy*.253,
                         z+top], axis=1)
    rows = [ring(f,z) for f,z in [(.15,.425),(.89,.425),(.975,.438),(1,.454),(1.005,.475),
                                  (.987,.495),(.94,.505),(.85,.510),(.64,.512),(.42,.512),(.20,.512),(.03,.512)]]
    skin(soft, rows, [0,1])
    swept(trim,ring(1.005,.461),.0023,True)


def upholstered_back(zmid, height, width, depth, front, mat, wing):
    a = np.arange(80)*2*np.pi/80
    x, z = superpoint(np.cos(a),.64),superpoint(np.sin(a),.64)
    def ring(f, yoff):
        xx,zz = f*x,f*z
        halfwidth=width*(1+.055*zz)
        return np.stack([2.8+halfwidth*xx, front+zz*.023-wing*xx**2+yoff,
                         zmid+zz*height],axis=1)
    # Continuous wrap and a rolled, bound perimeter. Positive Y is the outside.
    rows=[ring(f,off*depth) for f,off in [(.03,1),(.65,1),(.9,.92),(.98,.72),(1,.45),
                 (.984,.21),(.93,.07),(.82,0),(.63,-.06),(.42,-.08),(.2,-.09),(.03,-.09)]]
    skin(mat,rows,[0,2])
    swept(trim,ring(.994,.37*depth),.0021,True)


